pub inline fn SUCCEEDED(Status: winnt.HRESULT) bool {
    return Status >= 0;
}
pub inline fn FAILED(Status: winnt.HRESULT) bool {
    return Status < 0;
}
pub inline fn IS_ERROR(Status: winnt.HRESULT) bool {
    return @as(xboxkrnl.xboxdef.ULONG, @bitCast(Status)) >> 31 == SEVERITY_ERROR;
}
pub inline fn HRESULT_CODE(r: winnt.HRESULT) winnt.HRESULT {
    return r & 0xFF_FF;
}
pub inline fn SCODE_CODE(c: winnt.SCODE) winnt.SCODE {
    return c & 0xFF_FF;
}
pub inline fn HRESULT_FACILITY(r: winnt.HRESULT) winnt.HRESULT {
    return (r >> 16) & 0x1F_FF;
}
pub inline fn SCODE_FACILITY(c: winnt.SCODE) winnt.SCODE {
    return (c >> 16) & 0x1F_FF;
}
pub inline fn HRESULT_SEVERITY(r: winnt.HRESULT) winnt.HRESULT {
    return (r >> 31) & 0x1;
}
pub inline fn SCODE_SEVERITY(c: winnt.SCODE) winnt.SCODE {
    return (c >> 31) & 0x1;
}
pub inline fn MAKE_HRESULT(sev: winnt.HRESULT, fac: winnt.HRESULT, code: winnt.HRESULT) winnt.HRESULT {
    return @bitCast(
        (@as(xboxkrnl.xboxdef.ULONG, @bitCast(sev)) << 31) |
        (@as(xboxkrnl.xboxdef.ULONG, @bitCast(fac)) << 16) |
        (@as(xboxkrnl.xboxdef.ULONG, @bitCast(code)) << 0),
    );
}
pub inline fn MAKE_SCODE(sev: winnt.SCODE, fac: winnt.SCODE, code: winnt.SCODE) winnt.SCODE {
    return (sev << 31) | (fac << 16) | (code << 0);
}
pub const FACILITY_NT_BIT = 0x10_00_00_00;
pub inline fn HRESULT_FROM_WIN32(x: winnt.SCODE) winnt.HRESULT {
    return if (x)
        @bitCast((x & 0x00_00_FF_FF) | (FACILITY_WIN32 << 16) | 0x80_00_00_00)
    else
        0;
}
pub inline fn HRESULT_FROM_NT(x: winnt.SCODE) winnt.HRESULT {
    return @bitCast(x | FACILITY_NT_BIT);
}
pub inline fn GetScode(hr: winnt.HRESULT) winnt.SCODE {
    return @bitCast(hr);
}
pub inline fn ResultFromScode(sc: winnt.SCODE) winnt.HRESULT {
    return @bitCast(sc);
}
pub inline fn PropagateResult(hrPrevious: winnt.HRESULT, scBase: winnt.SCODE) winnt.HRESULT {
    _ = hrPrevious;
    return @bitCast(scBase);
}

